/* Adds the light of the volumes to each drawn vertex of the vertex lists: the vertex (moved by its
 * own packed matrix when multiple) is lit by each volume holding it. The last animated volume
 * found sets the vertex's animation bits: pattern 4..6 from the volume's seed (mode 1) or from
 * the vertex position (mode 2), and a level from the volume's strength there. */
void Actors_AccumulateVertexLighting(LightVolume **lights, s32 lightCount, s32 *lists, void *matrices, CVector3 *output, s32 multiple) {
    f32 matrix[16];
    CVector3 sum;
    CVector3 position;
    CVector3 normal;
    CVector3 worldPosition;
    CVector3 worldNormal;
    CVector3 contribution;
    f32 amount;
    f32 selectedAmount;
    s32 n;
    s32 i;
    s32 j;
    s32 mode;
    s32 colour;
    s32 level;
    s32 drawn;
    CVector3 *dest;
    u32 pattern;
    PackedVertex *vertex;
    PackedVertex *base;
    VertexList *list;
    LightVolume *light;

    CMtxF__FromMtxAffine(matrix, matrices);
    drawn = 0;
    for (n = 0; n < *lists; n++) {
        list = CISet__GetBlock(lists, n);
        base = list->vertices;
        for (i = 0; i < list->count; i++) {
            vertex = &base[i];
            dest = &output[drawn];
            mode = 0;
            selectedAmount = 0.0f;
            colour = 0;
            if (vertex->flags & 0x80) {
                continue;
            }
            if (multiple) {
                CMtxF__FromMtxAffine(matrix, (u8 *)matrices + ((vertex->flags >> 8) << 6));
            }
            position.x = vertex->px;
            position.y = vertex->py;
            position.z = vertex->pz;
            CMtxF__TransformPoint(matrix, &position, &worldPosition);
            normal.x = vertex->nx;
            normal.y = vertex->ny;
            normal.z = vertex->nz;
            CMtxF__RotateVector(matrix, &normal, &worldNormal);
            sum.x = 0.0f;
            sum.y = 0.0f;
            sum.z = 0.0f;
            for (j = 0; j < lightCount; j++) {
                light = lights[j];
                contribution.x = 0.0f;
                contribution.y = 0.0f;
                contribution.z = 0.0f;
                if (light->max.x > worldPosition.x &&
                    light->max.y > worldPosition.y &&
                    light->max.z > worldPosition.z &&
                    light->min.x <= worldPosition.x &&
                    light->min.y <= worldPosition.y &&
                    light->min.z <= worldPosition.z &&
                    Actors_EvaluateLightVolume(light, worldPosition, worldNormal, light->inverse, &contribution, &amount)) {
                    if (light->animatedLight) {
                        mode = light->animatedLight;
                        colour = light->animationSeed;
                        selectedAmount = amount;
                    }
                    CVector3__Add(&sum, &sum, &contribution);
                }
            }
            if (mode) {
                level = 0;
                if (selectedAmount < 0.6f) {
                    level = 1;
                }
                if (selectedAmount < 0.3f) {
                    level = 2;
                }
                if (mode == 1) {
                    vertex->flags = (vertex->flags & 0xFF8F) | (((colour % 7 + 1) << 4) & 0x70);
                }
                if (mode == 2) {
                    pattern = 0;
                    pattern += T2_F2U(worldPosition.x) / 10;
                    pattern += T2_F2U(worldPosition.y) / 10;
                    pattern += T2_F2U(worldPosition.z) / 10;
                    pattern = pattern % 7 + 1;
                    vertex->flags = (vertex->flags & 0xFF8F) | ((pattern << 4) & 0x70);
                }
                vertex->flags = (vertex->flags & 0xFFF3) | (level << 2);
                if (selectedAmount < 0.1f) {
                    vertex->flags &= 0xFF83;
                }
            }
            dest->x += sum.x;
            dest->y += sum.y;
            dest->z += sum.z;
            drawn++;
        }
    }
}

/* Debug coloring: each vertex gets a hue from its transformed position along
 * the (1,1,1) diagonal. */
void Lighting_DebugHueColors(s32 *model, u8 *matrices, CVector3 *colors, s32 skinned) {
    f32 mtx[16];
    CVector3 axis;
    ColorF c;
    CVector3 in;
    CVector3 out;
    VertexGroup *group;
    ModelVtx *verts;
    s32 n;
    f32 hue;
    s32 i;
    s32 j;

    n = 0;
    CMtxF__FromMtxAffine(mtx, matrices);
    axis.x = 1.0f;
    axis.y = 1.0f;
    axis.z = 1.0f;
    CVector3__Normalize(&axis);
    for (i = 0; i < *model; i++) {
        group = CISet__GetBlock(model, i);
        verts = group->verts;
        for (j = 0; j < group->count; j++) {
            if (skinned) {
                CMtxF__FromMtxAffine(mtx, matrices + (verts[j].v.flag >> 8) * 64);
            }
            in.x = verts[j].v.ob[0];
            in.y = verts[j].v.ob[1];
            in.z = verts[j].v.ob[2];
            CMtxF__TransformPoint(mtx, &in, &out);
            hue = out.x * axis.x + out.y * axis.y + out.z * axis.z;
            hue /= 1024.0f;
            c = Color_HSVToRGB(hue, 1.0f, 1.0f);
            colors[n].x = c.r * 255.0f;
            colors[n].y = c.g * 255.0f;
            colors[n].z = c.b * 255.0f;
            n++;
        }
    }
}

typedef struct {
    u8 r, g, b, a;
} Color4;
#define MIN(a, b) ((a) < (b) ? (a) : (b))

/* Copies every vertex color of the model into `colors`, clamped to 30..225. */
void Lighting_CopyVertexColors(s32 *model, Color4 *colors) {
    VertexGroup *group;
    ModelVtx *verts;
    Color4 *c;
    s32 i;
    s32 j;
    s32 n;
    u8 x;
    s32 k;

    k = 0;
    for (i = 0; i < *model; i++) {
        group = CISet__GetBlock(model, i);
        verts = group->verts;
        n = group->count;
        for (j = 0; j < n; j++) {
            c = &colors[k++];
            do {
                x = verts[j].v.cn[0];
                c->r = MIN(verts[j].v.cn[0], 225) < 31 ? 30 : MIN(x, 225);
            } while (0);
            x = verts[j].v.cn[1];
            c->g = MIN(verts[j].v.cn[1], 225) < 31 ? 30 : MIN(x, 225);
            x = verts[j].v.cn[2];
            c->b = MIN(verts[j].v.cn[2], 225) < 31 ? 30 : MIN(x, 225);
        }
    }
}

typedef struct {
    /* 0x00 */ u8 pad0[0x11];
    /* 0x11 */ s8 lightX, lightY, lightZ;
} LightInfo;

/* Adds directional light to the model's vertex colors: each lit vertex's
 * rotated normal against the light direction, plus an ambient term. */
void Lighting_ApplyDirectional(s32 *model, u8 *matrices, CVector3 *colors, s32 skinned) {
    CVector3 light;
    f32 mtx[16];
    CVector3 in;
    CVector3 out;
    VertexGroup *group;
    ModelVtx *verts;
    f32 level;
    s32 n;
    s32 i;
    s32 j;
    s32 count;

    CMtxF__FromMtxAffine(mtx, matrices);
    light.x = ((LightInfo *)gScene.m_pLevelHeader)->lightX;
    n = 0;
    light.y = ((LightInfo *)gScene.m_pLevelHeader)->lightY;
    light.z = ((LightInfo *)gScene.m_pLevelHeader)->lightZ;
    CVector3__Normalize(&light);
    for (i = 0; i < *model; i++) {
        group = CISet__GetBlock(model, i);
        count = group->count;
        verts = group->verts;
        for (j = 0; j < count; j++) {
            if (verts[j].v.flag & 0x80) {
                continue;
            }
            if (skinned) {
                CMtxF__FromMtxAffine(mtx, matrices + (verts[j].v.flag >> 8) * 64);
            }
            in.x = verts[j].n.n[0];
            in.y = verts[j].n.n[1];
            in.z = verts[j].n.n[2];
            CMtxF__RotateVector(mtx, &in, &out);
            level = out.x * light.x + out.y * light.y + out.z * light.z;
            /* clamp at 0, then add the ambient term */
            level = ((level < 0.0f ? 0.0f : level) + 0.21960786f) * 255.0f;
            colors[n].x += level;
            colors[n].y += level;
            colors[n].z += level;
            n++;
        }
    }
}

