/* acos lookup: 1024 samples of acos over [0, 1]. */

f32 Math_AcosLookup(f32 x) {
    s32 neg;
    f32 pos;
    f32 lo;
    f32 r;
    s32 i;

    if (x < 0.0f) {
        neg = 1;
        pos = x * -1023.0f;
    } else {
        pos = x * 1023.0f;
        neg = 0;
    }
#ifdef TARGET_PORT
    /* MIPS trunc.w.s gives 0x7FFFFFFF for a NaN or an out-of-range value (the lookup then takes
     * its end branch); x86 cvttss2si gives INT_MIN, a negative table index (a NaN reaches here
     * from CVector3__GetYaw of a zero-length path step in the Mother boss level). */
    i = (pos == pos && pos < 2147483648.0f) ? (s32) pos : 0x7FFFFFFF;
#else
    i = pos;
#endif
    if ((f32) i < 1023.0f) {
        lo = gAcosTable[i];
        r = lo + (pos - (f32) i) * (*(&gAcosTable[i] + 1) - lo);
        if (neg) {
            return 3.1415927f - r;
        }
        return r;
    }
    if (neg) {
        return 3.1415927f - gAcosTable[1023];
    }
    return gAcosTable[1023];
}

/* Moves value by delta, clamped to [-limit, limit]; reversing direction is damped. */
f32 Math_StepClamped(f32 value, f32 delta, f32 limit) {
    if (delta < 0.0f && value <= -limit) {
        return value;
    }
    if (delta > 0.0f && limit <= value) {
        return value;
    }
    if ((value < 0.0f && delta > 0.0f) || (value > 0.0f && delta < 0.0f)) {
        delta *= 1.5f;
    }
    value += delta * gFrameIncrement;
    if (delta < 0.0f) {
        if (value < -limit) {
            value = -limit;
        }
    } else if (limit < value) {
        value = limit;
    }
    return value;
}

/* Moves value toward zero by rate * gFrameIncrement without overshooting. */
f32 Math_DecayToZero(f32 value, f32 rate) {
    if (value > 0.0f) {
        value -= rate * gFrameIncrement;
        if (value < 0.0f) {
            value = 0.0f;
        }
    } else if (value < 0.0f) {
        value += rate * gFrameIncrement;
        if (value > 0.0f) {
            value = 0.0f;
        }
    }
    return value;
}

/* Moves value toward target by rate * gFrameIncrement without overshooting. */
f32 Math_Approach(f32 value, f32 target, f32 rate) {
    if (value < target) {
        value += rate * gFrameIncrement;
        if (value > target) {
            value = target;
        }
    } else if (value > target) {
        value -= rate * gFrameIncrement;
        if (value < target) {
            value = target;
        }
    }
    return value;
}

/* Eases *value toward target by (target - *value) * rate * gFrameIncrement; snaps when rate is 1. */
void Math_EaseToward(f32 *value, f32 target, f32 rate) {
    f32 current;
    f32 step;

    current = *value;
    step = (target - current) * rate * gFrameIncrement;
    if (rate == 1.0f) {
        *value = target;
    } else if (current < target) {
        *value = current + step;
        if (*value > target) {
            *value = target;
        }
    } else if (current > target) {
        *value = current + step;
        if (*value < target) {
            *value = target;
        }
    }
}

