s32 IsCodePointer(uptr address);   /* nonzero for a code address */
/* What Crash_PrintStack reads of the faulting thread's ThreadContext (Crash_ShowScreen). */
typedef struct {
    /* 0x00 */ u8 pad0[0xD4];
    /* 0xD4 */ u32 *sp;             /* the saved stack pointer (low word of ThreadContext.sp) */
} StackContext;

/* Debug console: dumps a thread's stack, its unused low part (filled with
 * fill) and the first five words on it that look like return addresses. */
void Crash_PrintStack(u8 *stack, s32 size, void *context, u8 fill) {
    u8 *low;
    u32 *top;
    u32 *sp;
    s32 count;

    top = (u32 *)(stack + size);
    low = stack;
    while (*low == fill) {
        low++;
    }
    putString("\n");
    putString("Call stack ");
    putString("(top:");
    putHex32((uptr)(stack + size));
    putString(" bot:");
    putHex32((uptr)stack);
    putString(" low:");
    putHex32((uptr)low);
    putString(")\n");
    sCrashTextColor = 0xF7A9;
    for (sp = ((StackContext *)context)->sp, count = 1; sp < top && count < 6; sp++) {
        if (IsCodePointer(*sp)) {
            putHex32(*sp);
            putString("\n");
            count++;
        }
    }
    sCrashTextColor = 0xA529;
}

