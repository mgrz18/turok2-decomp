static __inline__ void packInit(AnimPack *pack, s32 count) {
    s32 index;
    s32 *ptr;
    s32 magic;

    index = 1;
    pack->count = count;
    pack->offsets[0] = ((count * 4) + 0xF) & ~7;
    if (count > 0) {
        magic = 0xDEADBEEF;
        ptr = pack->offsets;
        do {
            ptr[1] = magic;
            index += 1;
            ptr += 1;
        } while (count >= index);
    }
}

static __inline__ void *packAdd(AnimPack *pack, void *src, s32 size) {
    s32 i;
    void *data;

    for (i = 0; i <= pack->count; i++) {
        if (pack->offsets[i] == 0xDEADBEEF) {
            break;
        }
    }
    i--;
    pack->offsets[i + 1] = pack->offsets[i] + size;
    data = (u8 *) pack + pack->offsets[i];
    if (src != NULL) {
        func_0029E460(data, src, size);
    }
    return data;
}

static __inline__ s32 decodeAnim(void *src, void *dst) {
    s32 ok;
    AnimHeader *h = CISet__GetBlock(src, 0);
    void *posSrc = CISet__GetBlock(src, 1);
    void *rotSrc = CISet__GetBlock(src, 2);
    AnimPack *posDst = CISet__GetBlock(dst, 1);
    AnimPack *rotDst = CISet__GetBlock(dst, 2);

    sAnimRawRange = 1;
    sAnimDecodeRotation = 0;
    sAnimRemapMin = -2000.0f;
    sAnimRemapMax = 2000.0f;
    sAnimDecodeUnkC = h->fC;
    if (Anim_DecodeTracks(posSrc, posDst, h->posTracks, 3, h->radius, h->encoding) == 0) {
        ok = 0;
    } else {
        sAnimRawRange = 0;
        sAnimDecodeRotation = 1;
        sAnimRemapMin = -1.0f;
        sAnimRemapMax = 1.0f;
        sAnimDecodeUnkC = h->fC;
        ok = Anim_DecodeTracks(rotSrc, rotDst, h->rotTracks, 4, h->radius, h->encoding) != 0;
    }
    return ok;
}

