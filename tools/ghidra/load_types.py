#!/usr/bin/env python3
"""Load the repo's struct headers into the Ghidra project's program.

GhidraMCP can type functions with a struct but cannot define one, so the
types come in here: common.h's typedefs and every include/structs/*.h are
flattened into one file (as tools/ghidra/turok2_types.h) and parsed into the
program's data types with Ghidra's own C parser, replacing any earlier
definition of the same name. The project is then saved.

The project must not be open elsewhere (the GUI, or tools/ghidra/serve.sh):
Ghidra locks it. Runs through PyGhidra, as serve.sh does.

Usage:
    tools/ghidra/load_types.py
"""

import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
PROJECT_DIR = Path(os.environ.get("GHIDRA_PROJECT_DIR",
                                  Path.home() / "Documents" / "Proyectos" / "turok2_ghidra"))
os.environ.setdefault("GHIDRA_INSTALL_DIR", "/opt/homebrew/Cellar/ghidra/12.1.4/libexec")
os.environ.setdefault("JAVA_HOME", "/opt/homebrew/opt/openjdk@21/libexec/openjdk.jdk/Contents/Home")


def flatten():
    """One self-contained header: the typedefs, then each struct header."""
    order = ["game_object.h", "gbi.h"]
    order += sorted(p.name for p in (ROOT / "include" / "structs").glob("*.h") if p.name not in order)
    out = ["/* Generated by tools/ghidra/load_types.py from include/. */"]
    out += [l for l in (ROOT / "include" / "common.h").read_text().splitlines() if l.startswith("typedef")]
    for name in order:
        text = (ROOT / "include" / "structs" / name).read_text()
        out += [l for l in text.splitlines() if not l.startswith("#")]
    path = ROOT / "tools" / "ghidra" / "turok2_types.h"
    path.write_text("\n".join(out) + "\n")
    return path


def main():
    header = flatten()
    import pyghidra
    pyghidra.start()
    from ghidra.app.util.cparser.C import CParserUtils
    from ghidra.program.model.data import DataTypeConflictHandler
    from ghidra.util.task import TaskMonitor
    from ghidra.base.project import GhidraProject

    project = GhidraProject.openProject(str(PROJECT_DIR), "turok2")
    try:
        program = project.openProgram("/", "turok2.us.elf", False)
        tx = program.startTransaction("load turok2 types")
        try:
            dtm = program.getDataTypeManager()
            res = CParserUtils.parseHeaderFiles([], [str(header)], [], [], dtm, TaskMonitor.DUMMY)
            print(f"parsed {header.name}: {res.successful()}  {res.getFormattedParseMessage(None)[:400] if not res.successful() else ''}")
            names = re.findall(r"^\}\s*(\w+)\s*;", header.read_text(), re.M)
            from java.util import ArrayList

            def present(n):
                hits = ArrayList()
                dtm.findDataTypes(n, hits)
                return hits.size() > 0

            found = [n for n in names if present(n)]
            print(f"{len(found)} of {len(names)} structs in the program: {' '.join(found)}")
        finally:
            program.endTransaction(tx, True)
        project.save(program)
        project.close(program)
    finally:
        project.close()
    return 0


if __name__ == "__main__":
    sys.exit(main())
