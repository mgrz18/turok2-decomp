#!/usr/bin/env python3
"""Give functions their real names: versions/names.us.txt into the build.

Each `name = 0xVRAM;` line (in versions/names.us.txt or
versions/names/*.us.txt) becomes a splat symbol (versions/symbols_names.us.txt,
tracked and listed in the yaml's symbol_addrs_path, so the regenerated asm
calls it by name) and replaces func_VRAM in every C file and header, in
versions/function_sizes.us.txt and in versions/manual_stubs.us.txt. The C
files keep their file names. Run make setup and make verify afterwards.

Usage:
    python3 tools/apply_names.py
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NAMES = ROOT / "versions" / "names.us.txt"
SYMS = ROOT / "versions" / "symbols_names.us.txt"
OLD = ROOT / "versions" / "symbol_addrs.us.txt"
VM2_NAMED = 0x0043CC14  # virtual_1's vram in the yaml (Makefile VIRTUAL_1_NAMED)
BEGIN, END = "// --- names.us.txt (tools/apply_names.py) ---", "// --- end names ---"


def main():
    names = {}
    seen = {}
    bad = []
    # names.us.txt plus one file per area in versions/names/ (so parallel
    # naming work never edits the same file).
    files = [NAMES] + sorted((ROOT / "versions" / "names").glob("*.us.txt"))
    for f in files:
        for line in f.read_text().splitlines():
            m = re.match(r"^(\w+)\s*=\s*0x([0-9A-Fa-f]+);", line)
            if not m:
                continue
            name, addr = m.group(1), int(m.group(2), 16)
            key = f"func_{addr:08X}"
            if key in names and names[key][0] != name:
                bad.append(f"0x{addr:08X} named twice: {names[key][0]}, {name} ({f.name})")
            if name in seen and seen[name] != addr:
                bad.append(f"{name} on two addresses: 0x{seen[name]:08X}, 0x{addr:08X} ({f.name})")
            names[key] = (name, addr)
            seen[name] = addr
    if bad:
        print("\n".join(bad), file=sys.stderr)
        return 1
    # The second VM module (virtual_1) is named from 0x43CC14 but linked
    # 0x39000 lower, so its C functions are defined at the link address. A
    # name splat may use as a reference target resolves there: data words that
    # only look like 0x44xxxx pointers would become the link address, and
    # splat lists such names in undefined_funcs_auto at the named address,
    # which overrides the C definition. Nothing in the ROM points at the named
    # addresses, so these names are labels only.
    def attrs(a):
        return " can_be_referenced:False" if VM2_NAMED <= a < 0x80000000 else ""
    SYMS.write_text("// Generated by tools/apply_names.py from versions/names.us.txt; edit that.\n"
                    + "".join(f"{n} = 0x{a:08X}; // type:func{attrs(a)}\n" for n, a in names.values()))
    # An earlier version wrote a block into the untracked symbol_addrs.us.txt.
    if OLD.exists():
        text = OLD.read_text()
        OLD.write_text(re.sub(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", "", text, flags=re.S))
    # The address scan names every function func_VRAM; a renamed one would
    # then have two names at one address. Drop the scan's entry.
    scan = ROOT / "versions" / "symbols_from_scan.us.txt"
    lines = scan.read_text().splitlines()
    kept = [l for l in lines if not re.match(r"^(" + "|".join(names) + r")\s*=", l)]
    scan.write_text("\n".join(kept) + "\n")
    pat = re.compile(r"\b(" + "|".join(map(re.escape, names)) + r")\b")
    changed = 0
    for path in list((ROOT / "src").rglob("*.c")) + list((ROOT / "include").rglob("*.h")):
        src = path.read_text()
        new = pat.sub(lambda m: names[m.group(1)][0], src)
        if new != src:
            path.write_text(new)
            changed += 1
    # function_sizes.us.txt gives some functions a size under their func_
    # name; left as is, splat sees two names at one address and the data
    # (jump tables, callback tables) keeps calling them func_VRAM.
    sizes = ROOT / "versions" / "function_sizes.us.txt"
    text = sizes.read_text()
    new = pat.sub(lambda m: names[m.group(1)][0], text)
    # A second size line for a second-module name must say the same, or
    # splat takes the reference back.
    new = re.sub(r"^(\w+ = 0x([0-9A-Fa-f]+); // type:func[^\n]*?)$",
                 lambda m: m.group(1) if "can_be_referenced" in m.group(1)
                 or m.group(1).split()[0].startswith("func_")
                 else m.group(1) + attrs(int(m.group(2), 16)),
                 new, flags=re.M)
    if new != text:
        sizes.write_text(new)
        changed += 1
    # N64Recomp's stub list names functions by their ELF symbol.
    stubs = ROOT / "versions" / "manual_stubs.us.txt"
    text = stubs.read_text()
    new = pat.sub(lambda m: names[m.group(1)][0], text)
    if new != text:
        stubs.write_text(new)
        changed += 1
    print(f"{len(names)} names; {changed} files renamed in")
    return 0


if __name__ == "__main__":
    sys.exit(main())
