#!/usr/bin/env python3
"""Generate port/runtime/t2_placeholders.c: WEAK placeholders for every symbol the linked game
still references but nothing defines (docs/port/LINK.md §2).

Data symbols become zero-filled weak arrays, functions weak stubs that call t2_missing() (log
once, return 0; abort with T2_MISSING_ABORT=1). The library is linked last, so any real
definition (game C, q2's generated data, the runtime) wins and the stale entries cost nothing.
This is a bring-up device: zero is the wrong value for most of these (function pointer tables,
descriptor records, the thread priorities), and LINK.md says what that means for a run.

Procedure (on the build box; the N64 ELF comes from the matching build):

  python3 tools/port/genplaceholders.py --reset                    # empty placeholder file
  ninja -C OUT turok2 > OUT/link.log 2>&1                          # fails: undefined references
  python3 tools/port/genplaceholders.py --log OUT/link.log --elf build/turok2.us.elf \\
      --lib OUT/libturok2_game.a --lib OUT/app/libt2runtime.a      # writes the file + summary
  ninja -C OUT turok2

A symbol is a function if some object calls it (an R_X86_64_PLT32 / R_AARCH64_CALL26
relocation in the given libraries), data otherwise. A data placeholder is sized from the N64
ELF: st_size, or the distance to the next symbol, doubled (pointer members widen) plus 64, at
least 128 bytes, aligned to 16; 256 bytes if the ELF does not know the name.
"""
import argparse, bisect, collections, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, 'port/runtime/t2_placeholders.c')

HEADER = '''/* GENERATED by tools/port/genplaceholders.py: do not edit (docs/port/LINK.md §2).
 *
 * WEAK placeholders for the symbols the linked game references and nothing defines yet:
 * %d data symbols (zero-filled) and %d functions (log once via t2_missing, return 0).
 * Linked last (t2placeholders), so every real definition wins. Zero is NOT the right value
 * for most of this data: these are a way to get a link and run to the first crash, nothing
 * more. q2's data generator (port/gen) replaces the data entries. */
void t2_missing(const char *name);
#define T2_DATA(name, size) __attribute__((weak, aligned(16))) unsigned char name[size];
#define T2_FUNC(name) __attribute__((weak)) long name(void) { t2_missing(#name); return 0; }
'''


def undefined_from_log(path):
    pats = [re.compile(r"undefined reference to [`']([^'`]+)'"),   # GNU ld
            re.compile(r'undefined symbol: (\S+)'),                 # lld
            re.compile(r'^\s+"_([^"]+)", referenced from')]        # ld64
    names = set()
    for line in open(path, errors='replace'):
        for p in pats:
            m = p.search(line)
            if m:
                names.add(m.group(1))
    return names


def called_names(libs):
    calls = set()
    for lib in libs:
        out = subprocess.run(['readelf', '-rW', lib], capture_output=True, text=True).stdout
        for line in out.splitlines():
            if 'PLT32' in line or 'CALL26' in line or 'JUMP26' in line:
                parts = line.split()
                if len(parts) >= 5:
                    calls.add(parts[4].split('@')[0])
    return calls


def elf_symbols(path):
    from elftools.elf.elffile import ELFFile
    e = ELFFile(open(path, 'rb'))
    secs = {i: s.name for i, s in enumerate(e.iter_sections())}
    syms = {}
    for s in e.get_section_by_name('.symtab').iter_symbols():
        if not s.name or s['st_info']['type'] in ('STT_FILE', 'STT_SECTION'):
            continue
        shndx = s['st_shndx']
        sec = 'ABS' if shndx == 'SHN_ABS' else secs.get(shndx, str(shndx)) if isinstance(shndx, int) else str(shndx)
        syms[s.name] = (s['st_value'], s['st_size'], sec)
    return syms


def category(name, info, func):
    if func:
        return 'function'
    if info is None:
        return 'unknown to the N64 ELF'
    addr, _, sec = info
    if sec.startswith('.code_rodata') or sec == '.gfx_ucode_data':
        return 'engine .rodata (.code_rodata*)'
    if sec.startswith('.libultra') or sec == '.ucode_copy2':
        return 'libultra .data'
    if sec.startswith('.virtual'):
        return 'module-1 data (.virtual)'
    if sec == 'ABS' and addr >= 0x80000000:
        return 'absolute KSEG0 (.data/.bss by address)'
    if sec == 'ABS' and 0x400000 <= addr < 0x500000:
        return 'absolute VM address (module-1 labels)'
    if sec == 'ABS':
        return 'absolute, ROM offset / constant'
    return 'other section ' + sec


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--reset', action='store_true', help='write an empty placeholder file')
    ap.add_argument('--log', help='linker output with the undefined references')
    ap.add_argument('--elf', default=os.path.join(ROOT, 'build/turok2.us.elf'))
    ap.add_argument('--lib', action='append', default=[], help='host libraries (call relocations)')
    ap.add_argument('-o', '--out', default=OUT)
    ap.add_argument('--list', help='also write "category<TAB>kind<TAB>name<TAB>size" lines here')
    a = ap.parse_args()

    if a.reset:
        open(a.out, 'w').write(HEADER % (0, 0))
        print('wrote empty', a.out)
        return
    if not a.log:
        ap.error('--log is required (or --reset)')
    names = undefined_from_log(a.log)
    calls = called_names(a.lib)
    syms = elf_symbols(a.elf)
    addrs = sorted({v[0] for v in syms.values()})

    rows = []
    for n in sorted(names):
        info = syms.get(n)
        func = n in calls
        size = 0
        if not func:
            if info is None:
                size = 256
            else:
                addr, st, _ = info
                if st:
                    gap = st
                else:
                    i = bisect.bisect_right(addrs, addr)
                    gap = addrs[i] - addr if i < len(addrs) else 0x100
                gap = min(max(gap, 4), 0x100000)
                size = (max(gap * 2 + 64, 128) + 15) & ~15
        rows.append((category(n, info, func), 'func' if func else 'data', n, size))

    nd = sum(1 for r in rows if r[1] == 'data')
    nf = len(rows) - nd
    with open(a.out, 'w') as f:
        f.write(HEADER % (nd, nf))
        cur = None
        for cat, kind, n, size in sorted(rows):
            if cat != cur:
                f.write('\n/* %s */\n' % cat)
                cur = cat
            f.write('T2_FUNC(%s)\n' % n if kind == 'func' else 'T2_DATA(%s, 0x%X)\n' % (n, size))
    if a.list:
        with open(a.list, 'w') as f:
            for r in sorted(rows):
                f.write('%s\t%s\t%s\t%d\n' % r)
    by = collections.Counter(r[0] for r in rows)
    print('%d undefined: %d data, %d functions -> %s' % (len(rows), nd, nf, os.path.relpath(a.out, ROOT)))
    for cat, n in by.most_common():
        print('  %5d  %s' % (n, cat))
    print('  functions:', ' '.join(r[2] for r in sorted(rows, key=lambda r: r[2]) if r[1] == 'func'))


if __name__ == '__main__':
    main()
